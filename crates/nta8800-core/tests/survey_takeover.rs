//! "Overnemen in projectmodel" for floors to the ground. The takeover keeps
//! the project's geometry, so a survey floor reaches the project calculation
//! only through the `ntaCalculation.groundFloors` entry of the project floor
//! the adviser pairs it with (`src/core/nta/SurveyTakeover.ts`,
//! `applyGroundFloors`). `training-data/nta8800-survey-takeover-ground.json`
//! holds the survey floor the kernel derives (the 2015 detached house with a
//! façade part against the ground, ISSO 82.1 §8.4) and the project entry the
//! takeover writes from it; `src/__tests__/survey-takeover-ground.test.tsx`
//! checks that the takeover writes exactly that entry. This test checks both
//! ends against the kernel: the survey still derives that floor, and a project
//! floor of the same area with that entry calculates with the heated basement
//! and the same ground conductance as the survey's own floor.
//!
//! `NTA_WRITE_TAKEOVER_FIXTURE=1` rewrites the fixture after a deliberate
//! change of the survey's derivation.

use nta8800_core::ground::{slab_on_ground_conductance, SlabOnGround};
use nta8800_core::opname::{assess_residential_survey, ResidentialSurvey};
use nta8800_core::project_performance::assess_project_performance;
use serde_json::{json, Value};

const SURVEY: &str = include_str!("../../../training-data/nta8800-opname-2015-detached.json");
const PROJECT: &str = include_str!("../../../training-data/nta8800-example-terraced-dwelling.json");
const FIXTURE_PATH: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../training-data/nta8800-survey-takeover-ground.json"
);

/// The members `applyGroundFloors` carries; ΔU_for of the basement is left
/// to the project's own envelope (8.38 with 8.2.1).
const CARRIED: [&str; 6] = [
    "exposedPerimeterM",
    "constructionResistanceM2kPerW",
    "edgeThermalBridges",
    "edgeInsulation",
    "below",
    "heatedBasement",
];

/// The survey's derived floor to the ground with a heated basement.
fn survey_floor() -> Value {
    let mut survey: Value = serde_json::from_str(SURVEY).unwrap();
    survey["envelope"]["surfaces"]
        .as_array_mut()
        .unwrap()
        .push(json!({
            "id": "kelderwand", "element": "facade", "boundary": {"kind": "ground"},
            "grossAreaM2": 24.0, "cavity": false, "insulation": {"kind": "none_or_unknown"},
            "depthBelowGroundM": 1.2, "groundFloorId": "begane-grondvloer",
            "sourceReference": "synthetic survey: wall against the ground",
        }));
    let survey: ResidentialSurvey = serde_json::from_value(survey).unwrap();
    let assessment = serde_json::to_value(assess_residential_survey(&survey)).unwrap();
    assert!(
        assessment["status"]
            .as_str()
            .is_some_and(|status| status.starts_with("calculated")),
        "survey: {}",
        assessment["status"]
    );
    let floor = assessment["derivedInput"]["spaceHeating"]["demand"]["transmission"]
        ["groundFloors"]
        .as_array()
        .unwrap()
        .iter()
        .find(|floor| floor["id"] == "begane-grondvloer")
        .expect("the survey floor")
        .clone();
    assert!(floor["heatedBasement"].is_object(), "{floor}");
    floor
}

/// The entry `applyGroundFloors` writes on a blank template entry with every
/// value accepted.
fn takeover_entry(floor: &Value) -> Value {
    let mut entry = json!({"surfaceId": "floor"});
    for key in CARRIED {
        // Null and an empty list (no edge insulation) mean "none" and are not written.
        let none = |value: &&Value| value.is_null() || value.as_array().is_some_and(Vec::is_empty);
        if let Some(value) = floor.get(key).filter(|value| !none(value)) {
            let mut value = value.clone();
            if key == "heatedBasement" {
                value
                    .as_object_mut()
                    .unwrap()
                    .remove("forfaitDeltaUWPerM2k");
            }
            entry[key] = value;
        }
    }
    entry["sourceReference"] = Value::from(format!(
        "basisopname, vloer begane-grondvloer: {}",
        floor["sourceReference"].as_str().unwrap_or_default()
    ));
    entry
}

fn fixture() -> Value {
    let floor = survey_floor();
    let expected = json!({
        "description": "Survey floor to the ground with a heated basement (2015 detached house plus a façade part against the ground) and the project groundFloors entry the takeover writes from it on a blank entry with every value accepted. Generated by crates/nta8800-core/tests/survey_takeover.rs.",
        "surveyFloor": floor,
        "projectEntry": takeover_entry(&floor),
    });
    if std::env::var("NTA_WRITE_TAKEOVER_FIXTURE").is_ok() {
        std::fs::write(
            FIXTURE_PATH,
            serde_json::to_string_pretty(&expected).unwrap() + "\n",
        )
        .unwrap();
    }
    expected
}

fn slab(value: &Value) -> SlabOnGround {
    serde_json::from_value(value.clone()).unwrap()
}

#[test]
fn the_committed_fixture_is_what_the_survey_derives() {
    let expected = fixture();
    let committed: Value = serde_json::from_str(
        &std::fs::read_to_string(FIXTURE_PATH)
            .expect("training-data/nta8800-survey-takeover-ground.json"),
    )
    .unwrap();
    assert_eq!(
        committed, expected,
        "the survey derives another floor; rerun with NTA_WRITE_TAKEOVER_FIXTURE=1 and check the takeover test"
    );
}

#[test]
fn a_taken_over_heated_basement_calculates_like_the_survey_floor() {
    let expected = fixture();
    let survey = &expected["surveyFloor"];
    let area = survey["areaM2"].as_f64().unwrap();

    let mut project: Value = serde_json::from_str(PROJECT).unwrap();
    let before = assess_project_performance(&project);
    assert_eq!(before.status, "calculated_unverified", "{:?}", before.gaps);
    // The project floor has the survey floor's area; the takeover writes the entry.
    for zone in project["zones"].as_array_mut().unwrap() {
        for surface in zone["surfaces"].as_array_mut().unwrap() {
            if surface["id"] == "floor" {
                surface["area"] = Value::from(area);
            }
        }
    }
    project["ntaCalculation"]["groundFloors"] = json!([expected["projectEntry"].clone()]);
    let after = assess_project_performance(&project);
    assert_eq!(after.status, "calculated_unverified", "{:?}", after.gaps);

    let derived = serde_json::to_value(after.derived_input.as_ref().unwrap()).unwrap();
    let floors = derived["spaceHeating"]["demand"]["transmission"]["groundFloors"]
        .as_array()
        .unwrap();
    assert_eq!(floors.len(), 1);
    let project_floor = &floors[0];
    // Every carried value arrives unchanged; the project fills ΔU_for itself.
    for key in CARRIED {
        let mut want = survey.get(key).cloned().unwrap_or(Value::Null);
        let mut got = project_floor.get(key).cloned().unwrap_or(Value::Null);
        if key == "heatedBasement" {
            want.as_object_mut().unwrap().remove("forfaitDeltaUWPerM2k");
            got.as_object_mut().unwrap().remove("forfaitDeltaUWPerM2k");
        }
        if key == "edgeInsulation" && want.is_null() {
            want = json!([]);
        }
        if key == "edgeInsulation" && got.is_null() {
            got = json!([]);
        }
        assert_eq!(got, want, "{key}");
    }
    assert!((project_floor["areaM2"].as_f64().unwrap() - area).abs() < 1e-9);

    // With the project's ΔU_for in both, the ground conductance is the survey's.
    let project_slab = slab(project_floor);
    let mut survey_slab = slab(survey);
    survey_slab
        .heated_basement
        .as_mut()
        .unwrap()
        .forfait_delta_u_w_per_m2k = project_slab
        .heated_basement
        .as_ref()
        .unwrap()
        .forfait_delta_u_w_per_m2k;
    let h_project = slab_on_ground_conductance(&project_slab).unwrap();
    let h_survey = slab_on_ground_conductance(&survey_slab).unwrap();
    assert!(
        (h_project - h_survey).abs() <= 1e-9 * h_survey.max(1.0),
        "{h_project} against {h_survey}"
    );

    // The taken-over floor changes the project's heat need.
    let heat = |assessment: &nta8800_core::project_performance::ProjectPerformanceAssessment| {
        serde_json::to_value(assessment).unwrap()["performance"]["annualHeatingAndCoolingNeedKwh"]
            .as_f64()
            .expect("heat need")
    };
    assert!(heat(&after) > 0.0 && heat(&before) > 0.0);
    assert_ne!(heat(&after), heat(&before));
}
