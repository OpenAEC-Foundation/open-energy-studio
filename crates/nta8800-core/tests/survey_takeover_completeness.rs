//! Review 57: "Overnemen in projectmodel" is complete for every example survey.
//!
//! Two committed fixtures tie the TypeScript takeover to the kernel:
//! - `training-data/nta8800-survey-takeover-derived.json` (written here) holds
//!   the input the kernel derives from every `nta8800-opname-*.json` survey;
//! - `training-data/nta8800-survey-takeover-written.json` (written by
//!   `src/__tests__/review57-takeover-completeness.test.ts`) holds what
//!   `surveyTakeover` writes from each derived input into an empty draft.
//!
//! This test runs each written draft through the project route twice: on an
//! empty project draft (every other member blank, so the blank search names
//! each gap) and on the example project's draft. It checks that no gap remains
//! on a member the takeover wrote, that every taken-over block arrives in the
//! project's derived input unchanged, and that with the survey's geometry put
//! back the project route derives the survey's input and its BENG values.
//!
//! `NTA_WRITE_TAKEOVER_FIXTURE=1` rewrites the derived fixture after a
//! deliberate change of a survey's derivation; then rerun the TypeScript test
//! with `OES_WRITE_TAKEOVER_FIXTURE=1`.

use nta8800_core::building_performance::{assess_building_performance, BuildingPerformanceInput};
use nta8800_core::opname::utility::{assess_utility_survey, UtilitySurvey};
use nta8800_core::opname::{assess_residential_survey, ResidentialSurvey};
use nta8800_core::project_performance::assess_project_performance;
use serde_json::{json, Map, Value};

const DATA: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../training-data");
const DERIVED: &str = "nta8800-survey-takeover-derived.json";
const WRITTEN: &str = "nta8800-survey-takeover-written.json";
const DWELLING: &str =
    include_str!("../../../training-data/nta8800-example-terraced-dwelling.json");
const OFFICE: &str = include_str!("../../../training-data/nta8800-example-office.json");

/// Geometry-bound members the takeover leaves to the project
/// (`NOT_TAKEN_OVER` in `src/core/nta/SurveyTakeover.ts`).
const GEOMETRY_TOP: [&str; 3] = [
    "totalUsableFloorAreaM2",
    "lossAreaM2",
    "lossAreaSourceReference",
];
const GEOMETRY_DEMAND: [&str; 8] = [
    "transmission",
    "opaqueElements",
    "opaqueInventoryComplete",
    "windows",
    "windowInventoryComplete",
    "usableFloorAreaM2",
    "areaSourceReference",
    "zoneId",
];

/// Chapter 11 ventilation members that follow the project zone.
const VENTILATION_GEOMETRY: [&str; 3] = ["zoneId", "usableFloorAreaM2", "functions"];

fn surveys() -> Vec<String> {
    let mut names: Vec<String> = std::fs::read_dir(DATA)
        .unwrap()
        .filter_map(|entry| entry.ok()?.file_name().into_string().ok())
        .filter(|name| {
            name.starts_with("nta8800-opname-") && !name.ends_with(".kernel-output.json")
        })
        .collect();
    names.sort();
    names
}

fn utility(name: &str) -> bool {
    name.contains("utility")
}

fn derive(name: &str) -> Value {
    let text = std::fs::read_to_string(format!("{DATA}/{name}")).unwrap();
    let assessment = if utility(name) {
        let survey: UtilitySurvey = serde_json::from_str(&text).unwrap();
        serde_json::to_value(assess_utility_survey(&survey)).unwrap()
    } else {
        let survey: ResidentialSurvey = serde_json::from_str(&text).unwrap();
        serde_json::to_value(assess_residential_survey(&survey)).unwrap()
    };
    let status = assessment["status"].as_str().unwrap_or_default();
    assert!(status.starts_with("calculated"), "{name}: {status}");
    assessment["derivedInput"].clone()
}

fn derived_fixture() -> Value {
    let cases: Map<String, Value> = surveys()
        .into_iter()
        .map(|name| {
            let derived = derive(&name);
            (name, derived)
        })
        .collect();
    let fixture = json!({
        "description": "The NTA input the kernel derives from every training-data/nta8800-opname-*.json survey. Generated by crates/nta8800-core/tests/survey_takeover_completeness.rs (NTA_WRITE_TAKEOVER_FIXTURE=1).",
        "derived": cases,
    });
    if std::env::var("NTA_WRITE_TAKEOVER_FIXTURE").is_ok() {
        std::fs::write(
            format!("{DATA}/{DERIVED}"),
            serde_json::to_string_pretty(&fixture).unwrap() + "\n",
        )
        .unwrap();
    }
    fixture
}

fn written() -> Value {
    let text = std::fs::read_to_string(format!("{DATA}/{WRITTEN}"))
        .expect("run src/__tests__/review57-takeover-completeness.test.ts with OES_WRITE_TAKEOVER_FIXTURE=1");
    serde_json::from_str(&text).unwrap()
}

fn example(name: &str) -> Value {
    serde_json::from_str(if utility(name) { OFFICE } else { DWELLING }).unwrap()
}

/// The example project with the taken-over draft of the written fixture: the
/// takeover into the example's own draft (`prefilled`), or into an empty draft
/// with every other member of the example's draft blank, so that the blank
/// search names each gap.
fn project_with(name: &str, case: &Value, prefilled: bool) -> Value {
    let mut project = example(name);
    let draft = if prefilled {
        &case["prefilled"]
    } else {
        &case["empty"]
    };
    let mut next = Map::new();
    if !prefilled {
        for key in project["ntaCalculation"].as_object().unwrap().keys() {
            next.insert(key.clone(), Value::Null);
        }
        // The edition stays the project's own.
        next.insert(
            "normVersion".into(),
            project["ntaCalculation"]["normVersion"].clone(),
        );
    }
    for (key, value) in draft.as_object().unwrap() {
        next.insert(key.clone(), value.clone());
    }
    project["ntaCalculation"] = Value::Object(next);
    project
}

#[test]
fn the_committed_derived_fixture_is_what_the_surveys_derive() {
    let expected = derived_fixture();
    let committed: Value =
        serde_json::from_str(&std::fs::read_to_string(format!("{DATA}/{DERIVED}")).expect(DERIVED))
            .unwrap();
    // Numbers compare to 1e-9: parsing JSON may move the last bit of a float.
    let mut diffs = Vec::new();
    differences(&committed, &expected, "", &mut diffs);
    assert!(
        diffs.is_empty(),
        "a survey derives another input; rerun with NTA_WRITE_TAKEOVER_FIXTURE=1, then the TypeScript test with OES_WRITE_TAKEOVER_FIXTURE=1:\n{}",
        diffs.join("\n")
    );
}

#[test]
fn every_survey_is_in_the_written_fixture() {
    let written = written();
    let names: Vec<&String> = written["written"].as_object().unwrap().keys().collect();
    assert_eq!(names, surveys().iter().collect::<Vec<_>>());
}

#[test]
fn no_gap_remains_on_a_member_the_takeover_wrote() {
    let written = written();
    for (name, case) in written["written"].as_object().unwrap() {
        let keys: Vec<&str> = case["keys"]
            .as_array()
            .unwrap()
            .iter()
            .map(|key| key.as_str().unwrap())
            .collect();
        for prefilled in [false, true] {
            let project = project_with(name, case, prefilled);
            let result = assess_project_performance(&project);
            let gaps = serde_json::to_value(&result.gaps).unwrap();
            for gap in gaps.as_array().unwrap() {
                let path = gap["path"].as_str().unwrap_or_default();
                let member = path
                    .strip_prefix("ntaCalculation.")
                    .unwrap_or(path)
                    .split(['.', '['])
                    .next()
                    .unwrap_or_default();
                assert!(
                    !keys.contains(&member),
                    "{name} (prefilled {prefilled}): gap {} on {path}, which the takeover wrote",
                    gap["code"]
                );
            }
            if prefilled {
                assert_eq!(
                    result.status, "calculated_unverified",
                    "{name}: {:?}",
                    result.gaps
                );
            }
        }
    }
}

/// Copies the project's `zoneId` and `areaM2`/`servedAreaM2` leaves into the
/// survey's value at the same places: the takeover gives lighting and
/// humidifiers the project zone and scales their areas to it.
fn zone_leaves(survey: &mut Value, project: &Value) {
    match (survey, project) {
        (Value::Object(a), Value::Object(b)) => {
            for (key, value) in a.iter_mut() {
                match b.get(key) {
                    Some(other)
                        if matches!(
                            key.as_str(),
                            "zoneId" | "areaM2" | "servedAreaM2" | "sportHallAreaM2"
                        ) =>
                    {
                        *value = other.clone()
                    }
                    Some(other) => zone_leaves(value, other),
                    None => {}
                }
            }
        }
        (Value::Array(a), Value::Array(b)) => {
            for (value, other) in a.iter_mut().zip(b) {
                zone_leaves(value, other);
            }
        }
        _ => {}
    }
}

/// Building facts a survey leaves blank; the project keeps its own value.
const BUILDING_FACTS: [&str; 8] = [
    "constructionYear",
    "labelFunction",
    "labelFunctions",
    "bblFunction",
    "bblFunctions",
    "activeCooling",
    "fossilAppliancesOutsideCalculation",
    "zebHeatDeliveryTemperature",
];

/// The survey's derived input with the project's geometry swapped in.
fn with_project_geometry(survey: &Value, project: &Value) -> Value {
    let mut next = survey.clone();
    for key in BUILDING_FACTS {
        let blank = |value: Option<&Value>| {
            value.map_or(true, |value| {
                value.is_null() || value.as_array().is_some_and(Vec::is_empty)
            })
        };
        if blank(next.get(key)) {
            match project.get(key) {
                Some(value) => next[key] = value.clone(),
                None => {
                    next.as_object_mut().unwrap().remove(key);
                }
            }
        }
    }
    zone_leaves(&mut next["lighting"], &project["lighting"]);
    zone_leaves(&mut next["hotWater"], &project["hotWater"]);
    zone_leaves(
        &mut next["additionalHotWaterSystems"],
        &project["additionalHotWaterSystems"],
    );
    zone_leaves(
        &mut next["spaceHeating"]["humidifiers"],
        &project["spaceHeating"]["humidifiers"],
    );
    for key in GEOMETRY_TOP {
        match project.get(key) {
            Some(value) => next[key] = value.clone(),
            None => {
                next.as_object_mut().unwrap().remove(key);
            }
        }
    }
    let demand = &project["spaceHeating"]["demand"];
    // Toepassen gives the chapter 11 ventilation the project zone's id and area
    // (syncVentilation), with the function areas over that area.
    if next["spaceHeating"]["demand"]["ventilation"].is_object() {
        for key in VENTILATION_GEOMETRY {
            next["spaceHeating"]["demand"]["ventilation"][key] = demand["ventilation"]
                .get(key)
                .cloned()
                .unwrap_or(Value::Null);
        }
    }
    for key in GEOMETRY_DEMAND {
        match demand.get(key) {
            Some(value) => next["spaceHeating"]["demand"][key] = value.clone(),
            None => {
                next["spaceHeating"]["demand"]
                    .as_object_mut()
                    .unwrap()
                    .remove(key);
            }
        }
    }
    next
}

/// Members whose values are text for people, not calculation input.
fn without_references(value: &Value) -> Value {
    match value {
        Value::Object(map) => Value::Object(
            map.iter()
                .filter(|(key, _)| {
                    !key.ends_with("ourceReference") && key.as_str() != "equipmentReference"
                })
                .map(|(key, inner)| (key.clone(), without_references(inner)))
                .collect(),
        ),
        Value::Array(items) => Value::Array(items.iter().map(without_references).collect()),
        other => other.clone(),
    }
}

/// Differences between two JSON values, as paths.
fn differences(a: &Value, b: &Value, path: &str, out: &mut Vec<String>) {
    match (a, b) {
        (Value::Object(x), Value::Object(y)) => {
            let mut keys: Vec<&String> = x.keys().chain(y.keys()).collect();
            keys.sort();
            keys.dedup();
            for key in keys {
                differences(
                    x.get(key).unwrap_or(&Value::Null),
                    y.get(key).unwrap_or(&Value::Null),
                    &format!("{path}.{key}"),
                    out,
                );
            }
        }
        (Value::Array(x), Value::Array(y)) if x.len() == y.len() => {
            for (index, (p, q)) in x.iter().zip(y).enumerate() {
                differences(p, q, &format!("{path}[{index}]"), out);
            }
        }
        (Value::Number(x), Value::Number(y)) => {
            let (x, y) = (x.as_f64().unwrap(), y.as_f64().unwrap());
            if (x - y).abs() > 1e-9 * x.abs().max(y.abs()).max(1.0) {
                out.push(format!("{path}: {x} / {y}"));
            }
        }
        _ if a != b => out.push(format!("{path}: {a} / {b}")),
        _ => {}
    }
}

#[test]
fn the_project_route_derives_the_survey_input_and_its_beng() {
    let derived = derived_fixture();
    let written = written();
    for (name, case) in written["written"].as_object().unwrap() {
        let survey = &derived["derived"][name];
        let project = project_with(name, case, true);
        let result = assess_project_performance(&project);
        assert_eq!(
            result.status, "calculated_unverified",
            "{name}: {:?}",
            result.gaps
        );
        let from_project = serde_json::to_value(result.derived_input.as_ref().unwrap()).unwrap();

        // The survey input with the project's geometry is what the project route derives.
        let want = without_references(&with_project_geometry(survey, &from_project));
        let got = without_references(&from_project);
        let mut diffs = Vec::new();
        differences(&got, &want, "", &mut diffs);
        assert!(
            diffs.is_empty(),
            "{name}: project route differs from the survey input:\n{}",
            diffs.join("\n")
        );

        // So, on the survey's own geometry, both routes give the same BENG.
        let mut survey_input: BuildingPerformanceInput =
            serde_json::from_value(survey.clone()).unwrap();
        let mut project_input = result.derived_input.clone().unwrap();
        project_input.total_usable_floor_area_m2 = survey_input.total_usable_floor_area_m2;
        project_input.loss_area_m2 = survey_input.loss_area_m2;
        project_input.space_heating.demand = survey_input.space_heating.demand.clone();
        project_input.lighting = survey_input.lighting.clone();
        project_input.hot_water = survey_input.hot_water.clone();
        project_input.additional_hot_water_systems =
            survey_input.additional_hot_water_systems.clone();
        project_input.space_heating.humidifiers = survey_input.space_heating.humidifiers.clone();
        survey_input.norm_version = project_input.norm_version;
        let beng = |input: &BuildingPerformanceInput| {
            let value = serde_json::to_value(assess_building_performance(input)).unwrap();
            (
                value["needIndicatorKwhPerM2Year"].clone(),
                value["primaryFossilIndicatorKwhPerM2Year"].clone(),
                value["renewableSharePercent"].clone(),
                value["indicativeLabelClass"].clone(),
            )
        };
        let (survey_beng, project_beng) = (beng(&survey_input), beng(&project_input));
        assert!(
            !survey_beng.0.is_null(),
            "{name}: no BENG 1 in the survey route"
        );
        assert_eq!(project_beng, survey_beng, "{name}");
    }
}
